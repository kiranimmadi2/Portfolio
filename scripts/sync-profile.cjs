// Generate crawlable static profile content. No runtime fetch or build service required.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const p = JSON.parse(fs.readFileSync(path.join(root, 'profile.json'), 'utf8'));
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const write = (file, text) => fs.writeFileSync(path.join(root, file), text, 'utf8');
const esc = value => String(value).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const url = file => new URL(p.cleanUrls ? file.replace(/\.html$/, '') : file, p.siteUrl).href;
const ref = id => ({ '@id': url('#' + id) });
fs.copyFileSync(path.join(root, p.portraitSource), path.join(root, p.portrait));
// Use the existing, visible KI logo at a stable URL for every theme and crawler.
fs.copyFileSync(path.join(root, p.faviconSource), path.join(root, p.favicon));
const icon = fs.readFileSync(path.join(root, p.favicon));
const iconWidth = icon.readUInt32BE(16), iconHeight = icon.readUInt32BE(20);
// Modern ICO files support a PNG frame; keep /favicon.ico consistent too.
const icoHeader = Buffer.alloc(22);
icoHeader.writeUInt16LE(1, 2);
icoHeader.writeUInt16LE(1, 4);
icoHeader[6] = iconWidth === 256 ? 0 : iconWidth;
icoHeader[7] = iconHeight === 256 ? 0 : iconHeight;
icoHeader.writeUInt16LE(1, 10);
icoHeader.writeUInt16LE(32, 12);
icoHeader.writeUInt32LE(icon.length, 14);
icoHeader.writeUInt32LE(22, 18);
fs.writeFileSync(path.join(root, 'favicon.ico'), Buffer.concat([icoHeader, icon]));
const png = fs.readFileSync(path.join(root, p.portrait));
const width = png.readUInt32BE(16), height = png.readUInt32BE(20);
const degree = `${p.education.degree} in ${p.education.field}`;
const graph = {
  '@context': 'https://schema.org',
  '@graph': [
    { '@type': 'WebSite', ...ref('website'), url: p.siteUrl, name: p.name, alternateName: [`${p.name} Portfolio`, new URL(p.siteUrl).hostname], publisher: ref('person'), inLanguage: 'en' },
    { '@type': 'ProfilePage', ...ref('webpage'), url: p.siteUrl, name: `${p.name} | AI Engineer & Forward Deployed Engineer Opportunities`, dateModified: p.updated + 'T00:00:00+05:30', isPartOf: ref('website'), mainEntity: ref('person'), primaryImageOfPage: ref('portrait'), description: p.summary },
    { '@type': 'Person', ...ref('person'), name: p.name, alternateName: p.handle, url: p.siteUrl, jobTitle: 'AI Engineer', description: p.summary, image: ref('portrait'), email: `mailto:${p.email}`, sameAs: p.sameAs, address: { '@type': 'PostalAddress', addressLocality: 'Bengaluru', addressRegion: 'Karnataka', addressCountry: 'IN' }, alumniOf: ref('university'), hasCredential: ref('degree'), knowsAbout: p.skills, subjectOf: { '@type': 'ProfilePage', url: url('about.html'), name: `About ${p.name}` } },
    { '@type': 'ImageObject', ...ref('portrait'), url: url(p.portrait), contentUrl: url(p.portrait), caption: p.portraitCaption, description: 'Profile photograph provided by Kiran Immadi for his official portfolio.', width, height, representativeOfPage: true },
    { '@type': 'CollegeOrUniversity', ...ref('university'), name: p.education.institution, url: p.education.url },
    { '@type': 'EducationalOccupationalCredential', ...ref('degree'), name: degree, credentialCategory: 'Bachelor degree', educationalLevel: 'Undergraduate', recognizedBy: ref('university'), about: { '@type': 'Thing', name: p.education.field, url: p.education.programUrl } },
    { '@type': 'ItemList', ...ref('selected-projects'), name: 'Selected AI engineering projects', itemListElement: p.projects.map((project, i) => ({ '@type': 'ListItem', position: i + 1, item: { '@type': 'SoftwareSourceCode', name: project.name, description: project.description, codeRepository: project.url, url: project.url, author: ref('person') } })) }
  ]
};
const json = JSON.stringify(graph, null, 2);
write('schema.json', json + '\n');

function metadata(title, description, canonical, type = 'website') {
  return `<!-- PROFILE METADATA START: generated by scripts/sync-profile.cjs -->
  <title>${esc(title)}</title>
  <meta name="description" content="${esc(description)}">
  <meta name="author" content="${esc(p.name)}">
  <meta name="application-name" content="${esc(p.name)}">
  <meta name="apple-mobile-web-app-title" content="${esc(p.name)}">
  ${p.googleSiteVerification ? `<meta name="google-site-verification" content="${esc(p.googleSiteVerification)}">` : ''}
  <meta name="robots" content="index, follow, max-image-preview:large, max-snippet:-1, max-video-preview:-1">
  <link rel="canonical" href="${canonical}">
  <link rel="icon" type="image/png" sizes="${iconWidth}x${iconHeight}" href="/${p.favicon}">
  <link rel="apple-touch-icon" sizes="${iconWidth}x${iconHeight}" href="/${p.favicon}">
  <link rel="alternate" type="text/plain" href="/llms.txt" title="Profile summary">
  <link rel="alternate" type="application/ld+json" href="/schema.json" title="Structured profile data">
  <link rel="sitemap" type="application/xml" href="/sitemap.xml">
  <meta property="og:type" content="${type}">
  <meta property="og:url" content="${canonical}">
  <meta property="og:site_name" content="${esc(p.name)}">
  <meta property="og:title" content="${esc(title)}">
  <meta property="og:description" content="${esc(description)}">
  <meta property="og:image" content="${url(p.portrait)}">
  <meta property="og:image:secure_url" content="${url(p.portrait)}">
  <meta property="og:image:type" content="image/png">
  <meta property="og:image:width" content="${width}">
  <meta property="og:image:height" content="${height}">
  <meta property="og:image:alt" content="${esc(p.portraitCaption)}">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:title" content="${esc(title)}">
  <meta name="twitter:description" content="${esc(description)}">
  <meta name="twitter:image" content="${url(p.portrait)}">
  <meta name="twitter:image:alt" content="${esc(p.portraitCaption)}">
  <!-- PROFILE METADATA END -->`;
}
let home = read('index.html');
home = home.replace(/<!-- PROFILE METADATA START:[\s\S]*?<!-- PROFILE METADATA END -->/, () => metadata(`${p.name} | AI Engineer & Forward Deployed Engineer Opportunities`, p.searchDescription, p.siteUrl, 'profile'));
home = home.replace(/<script type="application\/ld\+json">[\s\S]*?<\/script>/, () => `<script type="application/ld+json">\n${json}\n  </script>`);
write('index.html', home);

const questions = [
  ['What is Kiran Immadi’s education?', `I completed a ${degree} at ${p.education.institution}.`],
  ['Which roles is Kiran Immadi interested in?', `I am open to ${p.targetRoles.join(', ')} opportunities. My focus is AI agents, LLM applications, RAG workflows, and software integration.`],
  ['Which is Kiran Immadi’s official profile image?', 'My selected official profile photograph is linked in the profile metadata and machine-readable profile files. My portfolio, GitHub handle kiranimmadi2, and linked professional profiles identify this profile.'],
  ['How can a recruiter contact Kiran Immadi?', `Email ${p.email} with the role, product problem, and team details. You can also find my GitHub and LinkedIn profiles below.`]
];

for (const [file, label, description] of [
  ['about.html', 'Education & AI Engineering Profile', `${p.name} completed B.Tech in CSE (AI & ML) at ${p.education.institution}. Explore his education and AI engineering background in Bengaluru, India.`],
  ['skills.html', 'AI, Python & Flutter Skills', 'AI engineering, Python, machine learning, and Flutter skills of Kiran Immadi, a B.Tech CSE (AI & ML) graduate from Dayananda Sagar University.'],
  ['projects.html', 'Software & AI Projects', 'Explore software and AI projects by Kiran Immadi. See the main portfolio for selected AI agents, document workflows, and MCP integration work.'],
  ['contact.html', 'Contact for AI Engineering Opportunities', 'Contact Kiran Immadi about AI Engineer, Generative AI Engineer, and Forward Deployed Engineer opportunities. Based in Bengaluru, India.']
]) {
  let html = read(file);
  const meta = metadata(`${p.name} | ${label}`, description, url(file));
  if (html.includes('<!-- PROFILE METADATA START:')) {
    html = html.replace(/<!-- PROFILE METADATA START:[\s\S]*?<!-- PROFILE METADATA END -->/, () => meta);
  } else {
    html = html.replace(/\s*<title>[\s\S]*?<\/title>/g, '').replace('</head>', `  ${meta}\n</head>`);
  }
  if (file === 'about.html') {
    html = html.replace(/<img\b[^>]*class="profile-image"[^>]*>/, () => `<img src="${esc(p.portrait)}" alt="${esc(p.portraitCaption)}" width="${width}" height="${height}" decoding="async" class="profile-image">`);
    const aboutGraph = { ...graph, '@graph': graph['@graph'].filter(n => n['@type'] !== 'ItemList').map(n => n['@type'] === 'ProfilePage' ? { ...n, '@id': url('about.html#webpage'), url: url('about.html'), name: 'About ' + p.name } : n) };
    html = html.replace(/<script type="application\/ld\+json">[\s\S]*?<\/script>/, () => '<script type="application/ld+json">' + JSON.stringify(aboutGraph, null, 2) + '</script>');
  }
  write(file, html);
}

const identity = `# ${p.name} — AI Engineer\n\n> ${p.summary}\n\nLast updated: ${p.updated}\n\n## Identity\n- Name: ${p.name}\n- GitHub handle: ${p.handle}\n- Location: ${p.location}\n- Portfolio: ${p.siteUrl}\n- Official profile: ${url('about.html')}\n- Selected official image: ${url(p.portrait)}\n- Image description: ${p.portraitCaption}. This is the profile photograph provided by Kiran Immadi.\n- Email: ${p.email}\n${p.sameAs.map(link => `- Professional profile: ${link}`).join('\n')}\n\n## Completed education\n- Degree: ${degree}\n- Institution: ${p.education.institution}\n- Status: ${p.education.status}\n- University website: ${p.education.url}\n- Official degree program: ${p.education.programUrl}\n\n## Role interests\n${p.targetRoles.join(', ')}. These describe opportunities sought; they are not a list of employment positions held.\n\n## Technical focus\n${p.skills.join(', ')}.\n\n## Selected projects\n${p.projects.map(project => `- [${project.name}](${project.url}): ${project.description}`).join('\n')}\n\n## Profile scope\nThis document describes Kiran Immadi associated with GitHub account kiranimmadi2 and the professional links above. The portfolio owner confirms the completed B.Tech; the university link describes the program, not an individual graduation record. The official image is the owner-selected photograph above. Employment seniority, client results, awards, and performance claims are not established by this profile.\n`;
write('llms.txt', identity);
write('llms-full.txt', identity + `\n## Recruiter summary\nKiran builds AI applications that connect models, tools, data, APIs, and user interfaces. His portfolio highlights agent workflows, document-oriented AI, and MCP tools. He is interested in applied AI roles involving discovery, prototyping, integration, deployment, and iteration with users. Review the linked source code to assess project scope and fit.\n\n## Profile questions\n${questions.map(([question, answer]) => `### ${question}\n${answer}`).join('\n\n')}\n`);
write('sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">
${['', 'about.html', 'skills.html', 'projects.html', 'contact.html'].map(file => `  <url><loc>${url(file)}</loc><lastmod>${p.updated}</lastmod>${!file || file === 'about.html' ? `<image:image><image:loc>${url(p.portrait)}</image:loc></image:image>` : ''}</url>`).join('\n')}
</urlset>\n`);
write('robots.txt', `# Crawler access for the official Kiran Immadi portfolio.\n# Serve this file at the origin root: /robots.txt.\nUser-agent: *\nAllow: /\n\nSitemap: ${url('sitemap.xml')}\n`);
console.log('Updated static profile, metadata, schema, AI context files, and sitemap.');
