function block(html, name, content) {
  const regex = new RegExp(`<!-- ${name} START -->[\\s\\S]*?<!-- ${name} END -->`);
  if (!regex.test(html)) throw new Error(`Missing ${name} content marker`);
  return html.replace(regex, () => `<!-- ${name} START -->\n${content}\n<!-- ${name} END -->`);
}
